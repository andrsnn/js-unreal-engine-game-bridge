import assert from 'node:assert/strict';
import {registerAudio, registryForGame} from '../Tools/register-audio.mjs';
import {createUnrealAudioCatalog} from '../JavaScript/UnrealAudioCatalog.mjs';

const bytes = Buffer.from('OggS\x00physical-test');
const cue = {files: ['G:/sfx/test/rail.ogg'], loop: false, spatial: true, bus: 'weapons', near: 3, far: 100, licence: 'CC0-1.0'};
const handoff = {version: 1, game: 'karvos', cues: {rifle: cue, 'drive-low': {...cue, loop: true, bus: 'engines'}, 'score-bed': {...cue, loop: true, spatial: false, bus: 'music'}}, aliases: {'sfx.rifle': 'rifle'}};
const pass5 = {...handoff, audioPass: 5, sourceCommit: 'calibrated-source', mix: {outputGain: .72}, eventControls: {weaponCycle: {cue: 'rifle', durationSeconds: .11}}};
const next = registryForGame(await registerAudio([pass5], {readFile: async () => bytes}), 'karvos');
assert.equal(next.audioPass, 5);
assert.equal(next.sourceCommit, pass5.sourceCommit);
assert.deepEqual(next.mix, pass5.mix);
assert.deepEqual(next.eventControls, pass5.eventControls);
const parity = registryForGame(await registerAudio([{...pass5, eventControls: undefined, mixerParity: {eventControls: pass5.eventControls}}], {readFile: async () => bytes}), 'karvos');
assert.deepEqual(parity.eventControls, pass5.eventControls);
assert.deepEqual(createUnrealAudioCatalog(parity).control('weaponCycle'), pass5.eventControls.weaponCycle);
const naval = registryForGame(await registerAudio([{...pass5, mix: undefined, mixerMetadata: {outputGain: .69}}], {readFile: async () => bytes}), 'karvos');
assert.deepEqual(naval.mix, {outputGain: .69});
await assert.rejects(() => registerAudio([{...handoff, audioPass: -1}], {readFile: async () => bytes}), /audio pass/);
const manifest = await registerAudio([handoff, {...handoff, game: 'unlit'}], {readFile: async () => bytes});
assert.notEqual(manifest.games.karvos.cues.rifle.sound, manifest.games.unlit.cues.rifle.sound);
assert.equal(manifest.games.karvos.cues.rifle.minDistance, 300);
assert.equal(manifest.games.karvos.cues.rifle.maxDistance, 10000);
assert.equal(manifest.games.karvos.cues.rifle.variants[0].sha256.length, 64);
assert.equal(manifest.games.karvos.cues['score-bed'].pitch, 1);
const catalog = createUnrealAudioCatalog(registryForGame(manifest, 'karvos'));
assert.equal(catalog.resolve('sfx.rifle').sound, catalog.resolve('rifle').sound);
const existing = {rifle: {mesh: '/Game/Weapon', sound: '/Game/OldSound'}};
assert.equal(catalog.mergeAssets(existing).rifle.mesh, '/Game/Weapon');
assert.equal(existing.rifle.sound, '/Game/OldSound');
assert.deepEqual(catalog.oneShot('rifle', {volume: .7, pitch: .98, position: [1, 2, 3]}), {kind: 'sound', key: 'rifle', volume: .7, pitch: .98, position: [1, 2, 3], parameters: {}});
assert.throws(() => catalog.oneShot('drive-low'), /persistent stoppable/);
assert.throws(() => catalog.oneShot('unknown'), /Unregistered/);
assert.throws(() => catalog.oneShot('rifle', {volume: NaN}), /Invalid/);
await assert.rejects(() => registerAudio([{...handoff, aliases: {a: 'b', b: 'a'}}], {readFile: async () => bytes}), /cyclic/);
await assert.rejects(() => registerAudio([{...handoff, aliases: {rifle: 'drive-low'}}], {readFile: async () => bytes}), /collides/);
await assert.rejects(() => registerAudio([handoff], {readFile: async () => Buffer.from('HTML')}), /Not an OGG/);
await assert.rejects(() => registerAudio([{...handoff, cues: {bad: {...cue, licence: undefined}}}], {readFile: async () => bytes}), /licence/);
console.log('PASS: native keys, per-game namespaces, coordinate conversion, source hashes, aliases, licence closure, registry merge and safe loop handling');
