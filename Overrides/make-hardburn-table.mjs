#!/usr/bin/env node
// Writes Overrides/hardburn-models.md: each Hard Burn ship and station model, the game keys that use it, its
// original Pixal3D source, the source's triangles and texture size, and the symmetry repair applied.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const sharp = createRequire('C:/Users/Aidan Anderson/falling-frontier-clone/node_modules/x.js')('sharp');
// Triangles and image sizes from the glTF itself when the source folder has no mesh-stats.json.
async function glbStats(file) {
  const b = fs.readFileSync(file), jl = b.readUInt32LE(12), j = JSON.parse(b.subarray(20, 20 + jl).toString()), bin = 20 + jl + 8;
  let triangles = 0;
  for (const m of j.meshes) for (const p of m.primitives) triangles += (p.indices !== undefined ? j.accessors[p.indices].count : j.accessors[p.attributes.POSITION].count) / 3;
  const textures = [];
  for (const img of j.images ?? []) { const v = j.bufferViews[img.bufferView]; const meta = await sharp(b.subarray(bin + (v.byteOffset ?? 0), bin + (v.byteOffset ?? 0) + v.byteLength)).metadata(); textures.push([meta.width, meta.height]); }
  return {triangles, textures};
}
const here = path.dirname(fileURLToPath(import.meta.url));
const list = JSON.parse(fs.readFileSync(path.join(here, 'hardburn.sources.json'), 'utf8')).sources.filter(s => !s.kind);
const rows = [];
for (const s of list) {
  const statsFile = path.join(path.dirname(s.source), 'mesh-stats.json');
  const stats = fs.existsSync(statsFile) ? JSON.parse(fs.readFileSync(statsFile, 'utf8')) : await glbStats(s.source);
  const tex = (stats.textures ?? []).map(t => t.join('x')).join(', ');
  const repair = s.receipt ? (s.receipt.includes('receipts-high') ? 'receipts-high' : 'sol-xhigh') : 'none';
  rows.push(`| ${s.keys.join(', ')} | ${s.source.replace(/\/pixal3d_textured\.glb$/, '')} | ${(stats.triangles ?? 0).toLocaleString('en-US')} | ${tex} | ${repair} |`);
}
const text = `# Hard Burn models in Unreal

Generated by Overrides/make-hardburn-table.mjs from hardburn.sources.json. Each row is one model the game loads,
the game keys that use it, and the exact Pixal3D original it was built from (AssetVault, by the SHA-256 the manifest records), which Unreal draws instead (each folder holds
pixal3d_textured.glb). Triangles and textures are the source's own. The symmetry repair column names the receipt
the game adopted for its runtime copy, which Tools/fidelity/symfix.mjs applies to the full-resolution source.

${list.length} models, ${list.filter(s => s.receipt).length} with symmetry repairs. The two fast-attack hulls (concept_tdf_kestrel and
concept_tdf_peregrine) have no Pixal3D original and keep the game's own model.

| Game keys | Original source | Triangles | Textures | Symmetry repair |
| --- | --- | ---: | --- | --- |
${rows.join('\n')}
`;
fs.writeFileSync(path.join(here, 'hardburn-models.md'), text);
console.log(`${rows.length} rows`);
